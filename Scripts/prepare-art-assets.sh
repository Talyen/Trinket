#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."
# shellcheck source=lib/media-assets.sh
source "Scripts/lib/media-assets.sh"

manifest="ArtManifest/curated-assets.tsv"
asset_catalog="Trinket/Assets.xcassets"
generated_dir="Packages/TrinketContent/Sources/TrinketContent/Generated"
content_dir="Packages/TrinketContent/Sources/TrinketContent/Abilities"
generated_swift="$generated_dir/ArtCatalog.generated.swift"
source_hashes_file="$generated_dir/ArtSourceHashes.generated.tsv"

heic_quality="${ART_HEIC_QUALITY:-80}"
thumb_dimension="${ART_THUMB_DIMENSION:-480}"
portrait_thumb_dimension="${ART_PORTRAIT_THUMB_DIMENSION:-960}"
max_dimension_override="${ART_MAX_DIMENSION:-}"
combatant_dimension="${ART_COMBATANT_DIMENSION:-${max_dimension_override:-1320}}"
ability_dimension="${ART_ABILITY_DIMENSION:-${max_dimension_override:-960}}"
item_dimension="${ART_ITEM_DIMENSION:-${max_dimension_override:-960}}"
slot_background_dimension="${ART_SLOT_BACKGROUND_DIMENSION:-${max_dimension_override:-720}}"
background_dimension="${ART_BACKGROUND_DIMENSION:-${max_dimension_override:-1600}}"
portrait_background_dimension="${ART_PORTRAIT_BACKGROUND_DIMENSION:-${max_dimension_override:-2752}}"
encounter_dimension="${ART_ENCOUNTER_DIMENSION:-${max_dimension_override:-1320}}"
resource_dimension="${ART_RESOURCE_DIMENSION:-${max_dimension_override:-256}}"
talent_dimension="${ART_TALENT_DIMENSION:-${max_dimension_override:-960}}"

if ! trinket_asset_require_manifest "$manifest"; then
  exit 1
fi

trinket_asset_preflight art

mkdir -p "$asset_catalog" "$generated_dir"

scratch="$(mktemp -d)"
cleanup() {
  local status=$?
  rm -rf "$scratch"
  for backup in "$asset_catalog"/*.imageset.old.$$; do
    [[ -d "$backup" ]] || continue
    imageset="${backup%.old.$$}"
    if [[ ! -e "$imageset" ]]; then
      mv -f "$backup" "$imageset"
    else
      rm -rf "$backup"
    fi
  done
  rm -rf "$asset_catalog"/*.imageset.tmp.$$ 2>/dev/null || true
  return "$status"
}
trap cleanup EXIT

touch "$scratch"/{combatants,abilities,items,slot_backgrounds,backgrounds,portrait_backgrounds} \
  "$scratch"/{encounters,resources,talents,active_assets,seen_ids,seen_assets,prune_pairs}

printf '%s\n' "# Generated by Scripts/prepare-art-assets.sh. Do not edit directly." > "$scratch/source_hashes"
printf '%s\n' "# asset_name	source_sha256	encode_profile" >> "$scratch/source_hashes"
trinket_asset_begin_state_lookup "$source_hashes_file"

trinket_asset_extract_swift_quoted_ids "$scratch/combatant_ids" \
  "$generated_dir/GameContentRoster.generated.swift" \
  "$generated_dir/GameContentEnemies.generated.swift"
trinket_asset_extract_swift_quoted_ids "$scratch/ability_ids" \
  "$content_dir/AbilityCatalog+Basic.swift" \
  "$content_dir/AbilityCatalog+Skill.swift" \
  "$content_dir/AbilityCatalog+Ultimate.swift"
trinket_asset_extract_swift_quoted_ids "$scratch/item_ids" \
  "$generated_dir/GameContentItemBases.generated.swift"

awk -F'\t' '$1 == "combatant" {print $2}' "$manifest" | LC_ALL=C sort -u > "$scratch/manifest_combatant_ids"
awk -F'\t' '$1 == "ability" {print $2}' "$manifest" | LC_ALL=C sort -u > "$scratch/manifest_ability_ids"
awk -F'\t' '$1 == "item" {print $2}' "$manifest" | sed -e 's/-astral$//' -e 's/-basic$//' | LC_ALL=C sort -u > "$scratch/manifest_item_ids"

check_manifest_ids_present() {
  local wanted="$1" actual="$2" subject="$3" reason="$4"
  local missing missing_id
  missing=$(comm -23 "$wanted" "$actual")
  if [[ -n "$missing" ]]; then
    while IFS= read -r missing_id; do
      [[ -n "$missing_id" ]] || continue
      echo "$subject '$missing_id' $reason." >&2
    done <<< "$missing"
    exit 1
  fi
}

# Art IDs must be backed by the content owner that consumes them. This
# catches stale manifest rows before conversion creates orphaned assets.
check_manifest_ids_present "$scratch/manifest_combatant_ids" "$scratch/combatant_ids" \
  "Combatant art id" "is not present in the generated roster or enemy catalog"
check_manifest_ids_present "$scratch/manifest_ability_ids" "$scratch/ability_ids" \
  "Ability art id" "is not present in an authored ability catalog"
check_manifest_ids_present "$scratch/manifest_item_ids" "$scratch/item_ids" \
  "Item art id" "has no generated item base"


# Only rewrite when missing or content differs so no-op --assets runs do not
# invalidate actool.
cat > "$scratch/contents_json" <<'JSON'
{
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
JSON
trinket_asset_commit_generated "$scratch/contents_json" "$asset_catalog/Contents.json"


processed_count=0
full_count=0
thumb_count=0

heic_from_source() {
  local src="$1" dst="$2" sz="$3"
  sips -s format heic -s formatOptions "$heic_quality" -Z "$sz" "$src" --out "$dst" >/dev/null
  sips -d all "$dst" >/dev/null 2>&1 || true
}

write_imageset() {
  local imageset="$1"
  local asset_name="$2"
  local output_file="$3"
  local source_file="$4"
  local dimension="$5"

  local staged backup
  staged="${imageset}.tmp.$$"
  backup="${imageset}.old.$$"
  rm -rf "$staged" "$backup"
  mkdir -p "$staged"
  output_file="$staged/$(basename "$output_file")"
  heic_from_source "$source_file" "$output_file" "$dimension"
  [[ -s "$output_file" ]] || { rm -rf "$staged"; return 1; }
  cat > "$staged/Contents.json" <<JSON
{
  "images" : [
    {
      "filename" : "$asset_name.heic",
      "idiom" : "universal"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
JSON
  if [[ -e "$imageset" ]]; then
    mv "$imageset" "$backup"
  fi
  if ! mv "$staged" "$imageset"; then
    [[ -e "$backup" ]] && mv "$backup" "$imageset"
    rm -rf "$staged"
    return 1
  fi
  rm -rf "$backup"
}

# Kind-specific catalog metadata; conversion policy stays in the media helpers.
# kind | scratch file | reference type | dictionary key | crop metadata | full dimension
catalog_schema="combatant combatants CombatantArtReference String focal $combatant_dimension
ability abilities AbilityArtReference String none $ability_dimension
item items ItemArtReference String none $item_dimension
slot_background slot_backgrounds SlotBackgroundArtReference ItemSlot none $slot_background_dimension
background backgrounds BackgroundArtReference String aspect $background_dimension
portrait_background portrait_backgrounds BackgroundArtReference String aspect $portrait_background_dimension
encounter encounters EncounterArtReference String none $encounter_dimension
resource resources ResourceArtReference String none $resource_dimension
talent talents TalentArtReference Keyword aspect $talent_dimension"

while IFS=$'\t' read -r kind id asset_name source_path focal_x focal_y || [[ -n "${kind:-}" ]]; do
  [[ -z "${kind:-}" || "$kind" == \#* ]] && continue

  while read -r catalog_kind catalog_file catalog_type catalog_key catalog_crop full_dimension; do
    [[ "$catalog_kind" != "$kind" ]] || break
  done <<< "$catalog_schema"
  if [[ "$catalog_kind" != "$kind" ]]; then
    echo "Unsupported art kind '$kind' for id '$id'." >&2
    exit 1
  fi

  if [[ -z "$id" || -z "$asset_name" || -z "$source_path" || -z "$focal_x" || -z "$focal_y" ]]; then
    echo "Manifest row is missing required fields for id '$id'." >&2
    exit 1
  fi

  trinket_asset_assert_unique "$scratch/seen_ids" "art id '$id' for kind '$kind'" "$kind:$id"
  if [[ ! "$asset_name" =~ ^[A-Za-z0-9_]+$ ]]; then
    echo "Asset name '$asset_name' should use only letters, numbers, and underscores." >&2
    exit 1
  fi
  trinket_asset_assert_unique "$scratch/seen_assets" "art asset name" "$asset_name"

  if [[ ! "$focal_x" =~ ^[0-9]+([.][0-9]+)?$ || ! "$focal_y" =~ ^[0-9]+([.][0-9]+)?$ ]] \
    || ! awk -v x="$focal_x" -v y="$focal_y" 'BEGIN { exit !(x >= 0 && x <= 1 && y >= 0 && y <= 1) }'; then
    echo "Focal values for '$id' must be numeric values between 0 and 1." >&2
    exit 1
  fi

  # Row-local allowlists stay per-row; cross-manifest id backing was
  # pre-validated in bulk above.
  case "$kind" in
    talent)
      case "$id" in
        physical|burn|stun|block|health|gold|holy|poison|bleed|leech|freeze|dodge|purge|cleanse|mana|deathsDoor) ;;
        *)
          echo "Talent art id '$id' is not a valid Keyword case." >&2
          exit 1
          ;;
      esac
      ;;
  esac

  want_thumb=false
  if trinket_asset_needs_thumb "$kind"; then
    want_thumb=true
  fi
  selected_thumb_dimension="$thumb_dimension"
  [[ "$kind" != "portrait_background" ]] || selected_thumb_dimension="$portrait_thumb_dimension"

  imageset="$asset_catalog/$asset_name.imageset"
  output_file="$imageset/$asset_name.heic"
  thumb_asset="${asset_name}_thumb"
  thumb_imageset="$asset_catalog/${thumb_asset}.imageset"
  thumb_output_file="$thumb_imageset/${thumb_asset}.heic"

  printf '%s\n' "$asset_name" >> "$scratch/active_assets"
  if $want_thumb; then
    printf '%s\n' "$thumb_asset" >> "$scratch/active_assets"
  fi

  source_file="$(trinket_asset_source_path "$source_path")"
  if ! trinket_asset_require_source_file "$id" "$source_file"; then
    exit 1
  fi

  source_file_hash="$(shasum -a 256 "$source_file" | awk '{print $1}')"
  # Output settings participate in invalidation so sizing-only pipeline changes
  # cannot silently leave stale oversized assets in the catalog.
  encode_profile="q${heic_quality}/full${full_dimension}/thumb${selected_thumb_dimension}/thumb:${want_thumb}"
  source_hash="$(printf '%s\t%s\t%s\t%s\t%s\n' \
    "$source_file_hash" "$heic_quality" "$full_dimension" "$selected_thumb_dimension" "$want_thumb" \
    | shasum -a 256 | awk '{print $1}')"
  trinket_asset_read_recorded_state recorded_hash recorded_profile "$asset_name"
  printf '%s\t%s\t%s\n' "$asset_name" "$source_hash" "$encode_profile" >> "$scratch/source_hashes"

  if [[ "${FORCE_ASSET_REENCODE:-0}" == "1" || "$recorded_hash" != "$source_hash" || ! -f "$output_file" ]] \
    || { $want_thumb && [[ ! -f "$thumb_output_file" ]]; }; then
    write_imageset "$imageset" "$asset_name" "$output_file" "$source_file" "$full_dimension"
    full_count=$((full_count + 1))
    if $want_thumb; then
      write_imageset "$thumb_imageset" "$thumb_asset" "$thumb_output_file" "$source_file" "$selected_thumb_dimension"
      thumb_count=$((thumb_count + 1))
    fi
  fi

  # Remove thumbnails for kinds that ship only the full-size variant.
  if ! $want_thumb && [[ -d "$thumb_imageset" ]]; then
    rm -rf "$thumb_imageset"
  fi

  if [[ "$catalog_crop" == aspect ]]; then
    source_aspect_ratio="$(sips -g pixelWidth -g pixelHeight "$output_file" | awk '/pixelWidth:/{w=$2} /pixelHeight:/{h=$2} END {printf "%.12f", w/h}')"
    if [[ ! "$source_aspect_ratio" =~ ^[0-9]+\.[0-9]+$ ]]; then
      echo "Could not determine aspect ratio for '$id' from '$output_file'." >&2
      exit 1
    fi
  fi

  escaped_id="$(trinket_asset_escape_swift_string "$id")"
  escaped_asset="$(trinket_asset_escape_swift_string "$asset_name")"
  if [[ "$kind" == "slot_background" ]]; then
    case "$id" in
      weapon|armor|accessory|trinket) ;;
      *)
        echo "Slot background id '$id' must be one of: weapon, armor, accessory, trinket." >&2
        exit 1
        ;;
    esac
  fi
  key="\"$escaped_id\""
  [[ "$catalog_key" == String ]] || key=".$id"
  {
    printf '        %s: %s(\n' "$key" "$catalog_type"
    printf '            imageName: "%s"' "$escaped_asset"
    if [[ "$catalog_crop" == aspect ]]; then
      printf ',\n            sourceAspectRatio: %s' "$source_aspect_ratio"
    fi
    if [[ "$catalog_crop" != none ]]; then
      printf ',\n            focalPoint: ArtFocalPoint(x: %s, y: %s)' "$focal_x" "$focal_y"
    fi
    printf '\n        ),\n'
  } >> "$scratch/$catalog_file"

  processed_count=$((processed_count + 1))
done < "$manifest"

{
  cat <<'SWIFT_HEADER'
// Generated by Scripts/prepare-art-assets.sh. Do not edit directly.

import TrinketCore

/// Normalized art crop anchor. Kept as Doubles so the catalog stays Sendable
/// without relying on SwiftUI `UnitPoint` Sendable conformance.
public struct ArtFocalPoint: Hashable, Sendable {
    public let x: Double
    public let y: Double

    public init(x: Double, y: Double) {
        self.x = x
        self.y = y
    }
}
SWIFT_HEADER

  seen_reference_types=" "
  while read -r catalog_kind catalog_file catalog_type catalog_key catalog_crop full_dimension; do
    [[ "$seen_reference_types" != *" $catalog_type "* ]] || continue
    seen_reference_types+="$catalog_type "
    printf '\npublic struct %s: Hashable, Sendable {\n    public let imageName: String\n' "$catalog_type"
    if [[ "$catalog_crop" == aspect ]]; then
      printf '    public let sourceAspectRatio: Double\n'
    fi
    if [[ "$catalog_crop" != none ]]; then
      printf '    public let focalPoint: ArtFocalPoint\n'
    fi
    if [[ "$catalog_kind" != resource && "$catalog_kind" != slot_background ]]; then
      cat <<'SWIFT_THUMB'

    public var thumbnailImageName: String? {
        "\(imageName)_thumb"
    }
SWIFT_THUMB
    fi
    printf '}\n'
  done <<< "$catalog_schema"

  printf '\npublic enum ArtCatalog {\n'
  while read -r catalog_kind catalog_file catalog_type catalog_key catalog_crop full_dimension; do
    property="${catalog_kind}ArtByID"
    [[ "$catalog_kind" != slot_background ]] || property=slotBackgroundArtByID
    [[ "$catalog_kind" != portrait_background ]] || property=portraitBackgroundArtByID
    if [[ -s "$scratch/$catalog_file" ]]; then
      printf '    public static let %s: [%s: %s] = [\n' "$property" "$catalog_key" "$catalog_type"
      cat "$scratch/$catalog_file"
      printf '    ]\n\n'
    else
      printf '    public static let %s: [%s: %s] = [:]\n\n' "$property" "$catalog_key" "$catalog_type"
    fi
  done <<< "$catalog_schema"
  printf '}\n\n'

  cat <<'SWIFT'
extension Combatant {
    public var artReference: CombatantArtReference? {
        ArtCatalog.combatantArtByID[id]
    }
}

extension Ability {
    public var artReference: AbilityArtReference? {
        ArtCatalog.abilityArtByID[id]
    }
}

extension Keyword {
    public var artReference: TalentArtReference? {
        ArtCatalog.talentArtByID[self]
    }
}

SWIFT

  # Quoted heredoc so Swift interpolations and comments are not shell-expanded.
  cat <<'SWIFT_EXTENSIONS'
extension InventoryItem {
    public var artReference: ItemArtReference? {
        // Catalog keys are template ids (e.g. crossbow-basic), not per-instance ids.
        // Uniques share their base item's Astral artwork.
        ArtCatalog.itemArtByID[templateID]
            ?? (rarity == .unique ? ArtCatalog.itemArtByID["\(baseType.id)-astral"] : nil)
            ?? ArtCatalog.itemArtByID["\(baseType.id)-\(rarity.rawValue)"]
            ?? baseType.previewArtReference
    }
}

extension ItemSlot {
    public var slotBackgroundReference: SlotBackgroundArtReference? {
        ArtCatalog.slotBackgroundArtByID[self]
    }
}

SWIFT_EXTENSIONS
  cat <<'SWIFT_NAMES'
public extension ArtCatalog {
    static let allImageNames: [String] = {
        var names = Set<String>()
SWIFT_NAMES
  while read -r catalog_kind catalog_file catalog_type catalog_key catalog_crop full_dimension; do
    property="${catalog_kind}ArtByID"
    [[ "$catalog_kind" != slot_background ]] || property=slotBackgroundArtByID
    [[ "$catalog_kind" != portrait_background ]] || property=portraitBackgroundArtByID
    printf '        names.formUnion(%s.values.map(\\.imageName))\n' "$property"
    if [[ "$catalog_kind" != resource && "$catalog_kind" != slot_background ]]; then
      printf '        names.formUnion(%s.values.compactMap(\\.thumbnailImageName))\n' "$property"
    fi
  done <<< "$catalog_schema"
  cat <<'SWIFT_NAMES'
        return names.sorted()
    }()

    static let allImageNamesSet: Set<String> = Set(allImageNames)
}
SWIFT_NAMES
} > "$scratch/generated"

trinket_asset_commit_generated "$scratch/generated" "$generated_swift"

trinket_asset_sort_state "$scratch/source_hashes" "$source_hashes_file"

# Prune orphaned assets with one bulk membership check instead of a grep
# per directory. Any imageset outside the active set goes, matching the
# orphan rule in check-unused-assets.py (accent/app-icon sets never match
# *.imageset, so they are unaffected).
shopt -s nullglob
for dir in "$asset_catalog"/*/*.imageset "$asset_catalog"/*.imageset; do
  [[ -d "$dir" ]] || continue
  foldername=$(basename "$dir")
  name="${foldername%.imageset}"
  printf '%s\t%s\n' "$name" "$dir" >> "$scratch/prune_pairs"
done
shopt -u nullglob
LC_ALL=C sort -t$'\t' -k1,1 -o "$scratch/prune_pairs" "$scratch/prune_pairs"
LC_ALL=C sort -u -o "$scratch/active_assets" "$scratch/active_assets"
while IFS=$'\t' read -r name dir; do
  [[ -n "${name:-}" && -n "${dir:-}" ]] || continue
  echo "Pruning orphaned asset: $(basename "$dir")"
  rm -rf "$dir"
done < <(join -t$'\t' -v 1 -1 1 -2 1 "$scratch/prune_pairs" "$scratch/active_assets")


echo "Prepared $processed_count curated art asset(s) (converted $full_count full / $thumb_count thumb this run; kind-aware variants)."

trinket_asset_record art
