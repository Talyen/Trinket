#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

manifest="ArtManifest/curated-assets.tsv"
asset_catalog="Trinket/Assets.xcassets"
generated_dir="Packages/TrinketContent/Sources/TrinketContent/Generated"
content_dir="Packages/TrinketContent/Sources/TrinketContent/Content"
generated_swift="$generated_dir/ArtCatalog.generated.swift"
source_hashes_file="$generated_dir/ArtSourceHashes.generated.tsv"

heic_quality="${ART_HEIC_QUALITY:-80}"
thumb_dimension="${ART_THUMB_DIMENSION:-480}"
max_dimension_override="${ART_MAX_DIMENSION:-}"
combatant_dimension="${ART_COMBATANT_DIMENSION:-${max_dimension_override:-1320}}"
ability_dimension="${ART_ABILITY_DIMENSION:-${max_dimension_override:-960}}"
item_dimension="${ART_ITEM_DIMENSION:-${max_dimension_override:-960}}"
slot_background_dimension="${ART_SLOT_BACKGROUND_DIMENSION:-${max_dimension_override:-720}}"
background_dimension="${ART_BACKGROUND_DIMENSION:-${max_dimension_override:-1600}}"
encounter_dimension="${ART_ENCOUNTER_DIMENSION:-${max_dimension_override:-1320}}"
resource_dimension="${ART_RESOURCE_DIMENSION:-${max_dimension_override:-256}}"
talent_dimension="${ART_TALENT_DIMENSION:-${max_dimension_override:-960}}"

if [[ ! -f "$manifest" ]]; then
  echo "Missing manifest: $manifest" >&2
  exit 1
fi

mkdir -p "$asset_catalog" "$generated_dir"

# Prior-run source digests (asset_name → sha256). Invalidation is content-based so
# exporters that preserve stale mtimes (e.g. Darkroom) still trigger reconvert.
previous_hashes_file=$(mktemp)
if [[ -f "$source_hashes_file" ]]; then
  # Skip header / comment lines.
  grep -v '^#' "$source_hashes_file" > "$previous_hashes_file" || true
fi
source_hashes_temp=$(mktemp)
printf '%s\n' "# Generated by Scripts/prepare-art-assets.sh. Do not edit directly." > "$source_hashes_temp"
printf '%s\n' "# asset_name	source_sha256" >> "$source_hashes_temp"


# Only rewrite when missing or content differs so no-op --assets runs do not
# invalidate actool.
contents_json_temp=$(mktemp)
cat > "$contents_json_temp" <<'JSON'
{
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
JSON
if [[ -f "$asset_catalog/Contents.json" ]] && cmp -s "$contents_json_temp" "$asset_catalog/Contents.json"; then
  rm -f "$contents_json_temp"
else
  mv "$contents_json_temp" "$asset_catalog/Contents.json"
fi

combatants_temp=$(mktemp)
abilities_temp=$(mktemp)
items_temp=$(mktemp)
slot_backgrounds_temp=$(mktemp)
backgrounds_temp=$(mktemp)
encounters_temp=$(mktemp)
resources_temp=$(mktemp)
talents_temp=$(mktemp)
active_assets_temp=$(mktemp)
seen_ids_temp=$(mktemp)
seen_assets_temp=$(mktemp)
generated_temp=$(mktemp)
cleanup() {
  rm -f "$previous_hashes_file" "$source_hashes_temp" "$contents_json_temp" "$combatants_temp" "$abilities_temp" "$items_temp" \
    "$slot_backgrounds_temp" "$backgrounds_temp" "$encounters_temp" "$resources_temp" "$talents_temp" "$active_assets_temp" \
    "$seen_ids_temp" "$seen_assets_temp" "$generated_temp"
  for backup in "$asset_catalog"/*.imageset.old.$$; do
    [[ -d "$backup" ]] || continue
    imageset="${backup%.old.$$}"
    if [[ ! -e "$imageset" ]]; then
      mv -f "$backup" "$imageset"
    else
      rm -rf "$backup"
    fi
  done
  rm -rf "$asset_catalog"/*.imageset.tmp.$$ 2>/dev/null || true
}
trap cleanup EXIT
processed_count=0
full_count=0
thumb_count=0

escape_swift_string() {
  printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

heic_from_source() {
  local src="$1" dst="$2" sz="$3"
  sips -s format heic -s formatOptions "$heic_quality" -Z "$sz" "$src" --out "$dst" >/dev/null
  sips -d all "$dst" >/dev/null 2>&1 || true
}

write_imageset() {
  local imageset="$1"
  local asset_name="$2"
  local output_file="$3"
  local source_file="$4"
  local dimension="$5"

  local staged backup
  staged="${imageset}.tmp.$$"
  backup="${imageset}.old.$$"
  rm -rf "$staged" "$backup"
  mkdir -p "$staged"
  output_file="$staged/$(basename "$output_file")"
  heic_from_source "$source_file" "$output_file" "$dimension"
  [[ -s "$output_file" ]] || { rm -rf "$staged"; return 1; }
  cat > "$staged/Contents.json" <<JSON
{
  "images" : [
    {
      "filename" : "$asset_name.heic",
      "idiom" : "universal"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
JSON
  if [[ -e "$imageset" ]]; then
    mv "$imageset" "$backup"
  fi
  if ! mv "$staged" "$imageset"; then
    [[ -e "$backup" ]] && mv "$backup" "$imageset"
    rm -rf "$staged"
    return 1
  fi
  rm -rf "$backup"
}

# Catalog usage drives which variants we ship:
# - every kind emits a full-size image
# - resource / slot_background: full only
# - combatant / ability / item / encounter / background: full + thumb
emit_thumb_for_kind() {
  case "$1" in
    resource|slot_background) return 1 ;;
    *) return 0 ;;
  esac
}

full_dimension_for_kind() {
  case "$1" in
    combatant) printf '%s\n' "$combatant_dimension" ;;
    ability) printf '%s\n' "$ability_dimension" ;;
    item) printf '%s\n' "$item_dimension" ;;
    slot_background) printf '%s\n' "$slot_background_dimension" ;;
    background) printf '%s\n' "$background_dimension" ;;
    encounter) printf '%s\n' "$encounter_dimension" ;;
    resource) printf '%s\n' "$resource_dimension" ;;
    talent) printf '%s\n' "$talent_dimension" ;;
  esac
}

while IFS=$'\t' read -r kind id asset_name source_path focal_x focal_y || [[ -n "${kind:-}" ]]; do
  [[ -z "${kind:-}" || "$kind" == \#* ]] && continue

  if [[ "$kind" != "combatant" && "$kind" != "ability" && "$kind" != "item" && "$kind" != "slot_background" && "$kind" != "background" && "$kind" != "encounter" && "$kind" != "resource" && "$kind" != "talent" ]]; then
    echo "Unsupported art kind '$kind' for id '$id'." >&2
    exit 1
  fi

  if [[ -z "$id" || -z "$asset_name" || -z "$source_path" || -z "$focal_x" || -z "$focal_y" ]]; then
    echo "Manifest row is missing required fields for id '$id'." >&2
    exit 1
  fi

  if grep -Fqx "$kind:$id" "$seen_ids_temp"; then
    echo "Duplicate art id '$id' for kind '$kind'." >&2
    exit 1
  fi
  printf '%s\n' "$kind:$id" >> "$seen_ids_temp"

  if [[ ! "$asset_name" =~ ^[A-Za-z0-9_]+$ ]]; then
    echo "Asset name '$asset_name' should use only letters, numbers, and underscores." >&2
    exit 1
  fi
  if grep -Fqx "$asset_name" "$seen_assets_temp"; then
    echo "Duplicate art asset name '$asset_name'." >&2
    exit 1
  fi
  printf '%s\n' "$asset_name" >> "$seen_assets_temp"

  if [[ ! "$focal_x" =~ ^[0-9]+([.][0-9]+)?$ || ! "$focal_y" =~ ^[0-9]+([.][0-9]+)?$ ]] \
    || ! awk -v x="$focal_x" -v y="$focal_y" 'BEGIN { exit !(x >= 0 && x <= 1 && y >= 0 && y <= 1) }'; then
    echo "Focal values for '$id' must be numeric values between 0 and 1." >&2
    exit 1
  fi

  # Art IDs must be backed by the content owner that consumes them. This
  # catches stale manifest rows before conversion creates orphaned assets.
  case "$kind" in
    combatant)
      if ! rg -Fq "id: \"$id\"" "$generated_dir/GameContentRoster.generated.swift" \
        && ! rg -Fq "id: \"$id\"" "$generated_dir/GameContentEnemies.generated.swift"; then
        echo "Combatant art id '$id' is not present in the generated roster or enemy catalog." >&2
        exit 1
      fi
      ;;
    ability)
      rg -Fq "id: \"$id\"" "$content_dir/AbilityCatalogBasic.swift" \
        "$content_dir/AbilityCatalogSkill.swift" \
        "$content_dir/AbilityCatalogUltimate.swift" || {
        echo "Ability art id '$id' is not present in an authored ability catalog." >&2
        exit 1
      }
      ;;
    item)
      base_id="${id%-astral}"
      base_id="${base_id%-basic}"
      rg -Fq "ItemBaseType(id: \"$base_id\"" "$generated_dir/GameContentItemBases.generated.swift" || {
        echo "Item art id '$id' has no generated item base '$base_id'." >&2
        exit 1
      }
      ;;
    talent)
      case "$id" in
        physical|burn|stun|block|health|gold|holy|poison|bleed|leech|freeze|dodge|purge|cleanse|mana|deathsDoor) ;;
        *)
          echo "Talent art id '$id' is not a valid Keyword case." >&2
          exit 1
          ;;
      esac
      ;;
  esac

  want_full=true
  want_thumb=false
  if emit_thumb_for_kind "$kind"; then
    want_thumb=true
  fi
  full_dimension="$(full_dimension_for_kind "$kind")"

  imageset="$asset_catalog/$asset_name.imageset"
  output_file="$imageset/$asset_name.heic"
  thumb_asset="${asset_name}_thumb"
  thumb_imageset="$asset_catalog/${thumb_asset}.imageset"
  thumb_output_file="$thumb_imageset/${thumb_asset}.heic"

  if $want_full; then
    printf '%s\n' "$asset_name" >> "$active_assets_temp"
  fi
  if $want_thumb; then
    printf '%s\n' "$thumb_asset" >> "$active_assets_temp"
  fi

  source_file="$source_path"
  if [[ ! -f "$source_file" ]]; then
    echo "Missing source file for '$id': $source_path" >&2
    exit 1
  fi

  source_file_hash="$(shasum -a 256 "$source_file" | awk '{print $1}')"
  # Output settings participate in invalidation so sizing-only pipeline changes
  # cannot silently leave stale oversized assets in the catalog.
  source_hash="$(printf '%s\t%s\t%s\t%s\t%s\n' \
    "$source_file_hash" "$heic_quality" "$full_dimension" "$thumb_dimension" "$want_thumb" \
    | shasum -a 256 | awk '{print $1}')"
  recorded_hash="$(awk -F$'\t' -v name="$asset_name" '$1 == name { print $2; exit }' "$previous_hashes_file")"
  printf '%s\t%s\n' "$asset_name" "$source_hash" >> "$source_hashes_temp"

  needs_convert=false
  if [[ "${FORCE_ASSET_REENCODE:-0}" == "1" ]]; then
    needs_convert=true
  elif [[ -z "$recorded_hash" || "$recorded_hash" != "$source_hash" ]]; then
    needs_convert=true
  else
    if $want_full && [[ ! -f "$output_file" ]]; then
      needs_convert=true
    fi
    if $want_thumb && [[ ! -f "$thumb_output_file" ]]; then
      needs_convert=true
    fi
  fi

  if $needs_convert; then
    if $want_full; then
      write_imageset "$imageset" "$asset_name" "$output_file" "$source_file" "$full_dimension"
      full_count=$((full_count + 1))
    fi
    if $want_thumb; then
      write_imageset "$thumb_imageset" "$thumb_asset" "$thumb_output_file" "$source_file" "$thumb_dimension"
      thumb_count=$((thumb_count + 1))
    fi
  fi

  # Remove the variant we no longer ship for this kind.
  if ! $want_full && [[ -d "$imageset" ]]; then
    rm -rf "$imageset"
  fi
  if ! $want_thumb && [[ -d "$thumb_imageset" ]]; then
    rm -rf "$thumb_imageset"
  fi

  escaped_id="$(escape_swift_string "$id")"
  escaped_asset="$(escape_swift_string "$asset_name")"
  escaped_thumb="$(escape_swift_string "$thumb_asset")"
  if [[ "$kind" == "combatant" ]]; then
    cat >> "$combatants_temp" <<SWIFT
        dict["$escaped_id"] = CombatantArtReference(
            imageName: "$escaped_asset",
            thumbnailImageName: "$escaped_thumb",
            focalPoint: ArtFocalPoint(x: $focal_x, y: $focal_y)
        )
SWIFT
  elif [[ "$kind" == "ability" ]]; then
    cat >> "$abilities_temp" <<SWIFT
        dict["$escaped_id"] = AbilityArtReference(
            imageName: "$escaped_asset",
            thumbnailImageName: "$escaped_thumb"
        )
SWIFT
  elif [[ "$kind" == "item" ]]; then
    cat >> "$items_temp" <<SWIFT
        dict["$escaped_id"] = ItemArtReference(
            imageName: "$escaped_asset",
            thumbnailImageName: "$escaped_thumb"
        )
SWIFT
  elif [[ "$kind" == "slot_background" ]]; then
    case "$id" in
      weapon|armor|accessory|trinket) ;;
      *)
        echo "Slot background id '$id' must be one of: weapon, armor, accessory, trinket." >&2
        exit 1
        ;;
    esac
    cat >> "$slot_backgrounds_temp" <<SWIFT
        dict[.$id] = SlotBackgroundArtReference(
            imageName: "$escaped_asset"
        )
SWIFT
  elif [[ "$kind" == "background" ]]; then
    cat >> "$backgrounds_temp" <<SWIFT
        dict["$escaped_id"] = BackgroundArtReference(
            imageName: "$escaped_asset",
            thumbnailImageName: "$escaped_thumb",
            focalPoint: ArtFocalPoint(x: $focal_x, y: $focal_y)
        )
SWIFT
  elif [[ "$kind" == "resource" ]]; then
    cat >> "$resources_temp" <<SWIFT
        dict["$escaped_id"] = ResourceArtReference(
            imageName: "$escaped_asset"
        )
SWIFT
  elif [[ "$kind" == "encounter" ]]; then
    cat >> "$encounters_temp" <<SWIFT
        dict["$escaped_id"] = EncounterArtReference(
            imageName: "$escaped_asset",
            thumbnailImageName: "$escaped_thumb"
        )
SWIFT
  elif [[ "$kind" == "talent" ]]; then
    cat >> "$talents_temp" <<SWIFT
        dict[.$id] = TalentArtReference(
            imageName: "$escaped_asset",
            thumbnailImageName: "$escaped_thumb"
        )
SWIFT
  fi

  processed_count=$((processed_count + 1))
done < "$manifest"

{
  cat <<'SWIFT_HEADER'
// Generated by Scripts/prepare-art-assets.sh. Do not edit directly.

import TrinketCore

/// Normalized art crop anchor. Kept as Doubles so the catalog stays Sendable
/// without relying on SwiftUI `UnitPoint` Sendable conformance.
public struct ArtFocalPoint: Hashable, Sendable {
    public let x: Double
    public let y: Double

    public init(x: Double, y: Double) {
        self.x = x
        self.y = y
    }
}
SWIFT_HEADER

  cat <<SWIFT

public struct CombatantArtReference: Hashable, Sendable {
    public let imageName: String
    public let thumbnailImageName: String?
    public let focalPoint: ArtFocalPoint
}

public struct AbilityArtReference: Hashable, Sendable {
    public let imageName: String
    public let thumbnailImageName: String?
}

public struct ItemArtReference: Hashable, Sendable {
    public let imageName: String
    public let thumbnailImageName: String?
}

public struct SlotBackgroundArtReference: Hashable, Sendable {
    public let imageName: String
}

public struct BackgroundArtReference: Hashable, Sendable {
    public let imageName: String
    public let thumbnailImageName: String?
    public let focalPoint: ArtFocalPoint
}

public struct ResourceArtReference: Hashable, Sendable {
    public let imageName: String
}

public struct EncounterArtReference: Hashable, Sendable {
    public let imageName: String
    public let thumbnailImageName: String?
}

public struct TalentArtReference: Hashable, Sendable {
    public let imageName: String
    public let thumbnailImageName: String?
}


public enum ArtCatalog {
    public static let combatantArtByID: [String: CombatantArtReference] = {
        var dict = [String: CombatantArtReference]()
$(cat "$combatants_temp")
        return dict
    }()

    public static let abilityArtByID: [String: AbilityArtReference] = {
        var dict = [String: AbilityArtReference]()
$(cat "$abilities_temp")
        return dict
    }()

    public static let itemArtByID: [String: ItemArtReference] = {
        var dict = [String: ItemArtReference]()
$(cat "$items_temp")
        return dict
    }()

    public static let slotBackgroundArtByID: [ItemSlot: SlotBackgroundArtReference] = {
        var dict = [ItemSlot: SlotBackgroundArtReference]()
$(cat "$slot_backgrounds_temp")
        return dict
    }()

    public static let backgroundArtByID: [String: BackgroundArtReference] = {
        var dict = [String: BackgroundArtReference]()
$(cat "$backgrounds_temp")
        return dict
    }()

    public static let encounterArtByID: [String: EncounterArtReference] = {
        var dict = [String: EncounterArtReference]()
$(cat "$encounters_temp")
        return dict
    }()

    public static let resourceArtByID: [String: ResourceArtReference] = {
        var dict = [String: ResourceArtReference]()
$(cat "$resources_temp")
        return dict
    }()

    public static let talentArtByID: [Keyword: TalentArtReference] = {
        var dict = [Keyword: TalentArtReference]()
$(cat "$talents_temp")
        return dict
    }()

}

extension Combatant {
    public var artReference: CombatantArtReference? {
        ArtCatalog.combatantArtByID[id]
    }
}

extension Ability {
    public var artReference: AbilityArtReference? {
        ArtCatalog.abilityArtByID[id]
    }
}

extension Keyword {
    public var artReference: TalentArtReference? {
        ArtCatalog.talentArtByID[self]
    }
}

SWIFT

  # Quoted heredoc so Swift interpolations and comments are not shell-expanded.
  cat <<'SWIFT_EXTENSIONS'
extension InventoryItem {
    public var artReference: ItemArtReference? {
        // Catalog keys are template ids (e.g. crossbow-basic), not per-instance ids.
        ArtCatalog.itemArtByID[templateID]
            ?? ArtCatalog.itemArtByID["\(baseType.id)-\(rarity.rawValue)"]
            ?? baseType.previewArtReference
    }
}

extension ItemSlot {
    public var slotBackgroundReference: SlotBackgroundArtReference? {
        ArtCatalog.slotBackgroundArtByID[self]
    }
}
SWIFT_EXTENSIONS
} > "$generated_temp"

if [[ -f "$generated_swift" ]] && cmp -s "$generated_temp" "$generated_swift"; then
  rm -f "$generated_temp"
else
  mv "$generated_temp" "$generated_swift"
fi

source_hashes_sorted=$(mktemp)
{
  head -n 2 "$source_hashes_temp"
  tail -n +3 "$source_hashes_temp" | LC_ALL=C sort -t $'\t' -k1,1
} > "$source_hashes_sorted"
if [[ -f "$source_hashes_file" ]] && cmp -s "$source_hashes_sorted" "$source_hashes_file"; then
  rm -f "$source_hashes_sorted"
else
  mv "$source_hashes_sorted" "$source_hashes_file"
fi

# Prune orphaned assets
shopt -s nullglob
for dir in "$asset_catalog"/*/*.imageset "$asset_catalog"/*.imageset; do
  [[ -d "$dir" ]] || continue
  foldername=$(basename "$dir")
  name="${foldername%.imageset}"

  case "$name" in
    hero_*|companion_*|enemy_*|ability_*|item_*|slot_*|bg_*|encounter_*|resource_*|talent_*)
      if ! grep -qx "$name" "$active_assets_temp"; then
        echo "Pruning orphaned asset: $foldername"
        rm -rf "$dir"
      fi
      ;;
  esac
done
shopt -u nullglob

rm -f "$combatants_temp" "$abilities_temp" "$items_temp" "$slot_backgrounds_temp" "$backgrounds_temp" "$encounters_temp" "$resources_temp" "$active_assets_temp" "$seen_ids_temp" "$seen_assets_temp" "$previous_hashes_file" "$source_hashes_temp"

echo "Prepared $processed_count curated art asset(s) (converted $full_count full / $thumb_count thumb this run; kind-aware variants)."
