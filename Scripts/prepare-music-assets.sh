#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

manifest="MusicManifest/music.tsv"
resources_dir="Trinket/Resources/Music"
generated_dir="Packages/TrinketContent/Sources/TrinketContent/Generated"
generated_swift="$generated_dir/MusicCatalog.generated.swift"
state_file="$generated_dir/MusicSourceHashes.generated.tsv"
bitrate="${MUSIC_AAC_BITRATE:-96000}"

if [[ ! -f "$manifest" ]]; then
  echo "Missing manifest: $manifest" >&2
  exit 1
fi

if ! command -v afconvert >/dev/null 2>&1; then
  echo "Missing required tool: afconvert" >&2
  exit 1
fi

mkdir -p "$resources_dir" "$generated_dir"

tracks_temp=$(mktemp)
menu_temp=$(mktemp)
battle_temp=$(mktemp)
boss_temp=$(mktemp)
seen_ids_temp=$(mktemp)
seen_assets_temp=$(mktemp)
seen_boss_ids_temp=$(mktemp)
active_tracks_temp=$(mktemp)
processed_count=0
state_temp="$state_file.tmp.$$"
state_was_present=false
if [[ -f "$state_file" ]]; then
  cp "$state_file" "$state_temp"
  state_was_present=true
else
  printf '%s\n' '# Generated by Scripts/prepare-music-assets.sh. Do not edit directly.' > "$state_temp"
  printf '%s\t%s\n' '# asset_name' 'source_sha256' >> "$state_temp"
fi
cleanup() {
  rm -f "$tracks_temp" "$menu_temp" "$battle_temp" "$boss_temp" "$seen_ids_temp" "$seen_assets_temp" \
    "$seen_boss_ids_temp" "$active_tracks_temp" "$state_temp" "$state_temp.next" "$state_temp.sorted" "${generated_temp:-}" \
    "$resources_dir"/.*.tmp.$$.* 2>/dev/null || true
}
trap cleanup EXIT

escape_swift_string() {
  printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

validate_identifier() {
  local label="$1" value="$2"
  if [[ ! "$value" =~ ^[A-Za-z0-9_][A-Za-z0-9_-]*$ ]]; then
    echo "$label '$value' should use letters, numbers, hyphens, or underscores, and start with a letter, number, or underscore." >&2
    exit 1
  fi
}

while IFS=$'\t' read -r kind id asset_name source_path boss_enemy_id looping volume_gain || [[ -n "${kind:-}" ]]; do
  [[ -z "${kind:-}" || "$kind" == \#* ]] && continue
  [[ "$boss_enemy_id" == "none" ]] && boss_enemy_id=""

  if [[ "$kind" != "menu" && "$kind" != "battle" && "$kind" != "boss" ]]; then
    echo "Unsupported music kind '$kind' for id '$id'." >&2
    exit 1
  fi

  if [[ -z "$id" || -z "$asset_name" || -z "$source_path" || -z "$looping" || -z "$volume_gain" ]]; then
    echo "Manifest row is missing required fields for id '$id'." >&2
    exit 1
  fi

  validate_identifier "Track id" "$id"
  validate_identifier "Asset name" "$asset_name"

  if grep -qx "$id" "$seen_ids_temp"; then
    echo "Duplicate music track id '$id'." >&2
    exit 1
  fi
  printf '%s\n' "$id" >> "$seen_ids_temp"

  if grep -qx "$asset_name" "$seen_assets_temp"; then
    echo "Duplicate music asset name '$asset_name'." >&2
    exit 1
  fi
  printf '%s\n' "$asset_name" >> "$seen_assets_temp"

  if [[ ! -f "$source_path" ]]; then
    echo "Missing source file for '$id': $source_path" >&2
    exit 1
  fi

  case "$looping" in
    true|false) ;;
    *)
      echo "Looping value for '$id' must be true or false." >&2
      exit 1
      ;;
  esac

  if [[ ! "$volume_gain" =~ ^[0-9]+([.][0-9]+)?$ ]]; then
    echo "Volume gain for '$id' must be numeric." >&2
    exit 1
  fi

  if [[ "$kind" == "boss" ]]; then
    if [[ -z "$boss_enemy_id" ]]; then
      echo "Boss music '$id' must include boss_enemy_id." >&2
      exit 1
    fi
    if ! awk -v id="$boss_enemy_id" '$0 ~ ("id: \"" id "\"") && $0 ~ /isBoss: true/ { found = 1 } END { exit !found }' Packages/TrinketContent/Sources/TrinketContent/Generated/GameContentEnemies.generated.swift; then
      echo "Boss music '$id' references missing or non-boss enemy '$boss_enemy_id'." >&2
      exit 1
    fi
    if grep -Fqx "$boss_enemy_id" "$seen_boss_ids_temp"; then
      echo "Duplicate boss music enemy id '$boss_enemy_id'." >&2
      exit 1
    fi
    printf '%s\n' "$boss_enemy_id" >> "$seen_boss_ids_temp"
  elif [[ -n "$boss_enemy_id" ]]; then
    echo "Only boss music may include boss_enemy_id; '$id' has '$boss_enemy_id'." >&2
    exit 1
  fi

  # Track active assets for pruning
  printf '%s\n' "$asset_name.m4a" >> "$active_tracks_temp"

  output_file="$resources_dir/$asset_name.m4a"

  source_hash="$(shasum -a 256 "$source_path" | awk '{print $1}')"
  recorded_hash="$(awk -F$'\t' -v name="$asset_name" '$1 == name { print $2; exit }' "$state_file" 2>/dev/null || true)"
  needs_convert=false
  if [[ "${FORCE_ASSET_REENCODE:-0}" == "1" ]] \
    || [[ "$state_was_present" == false && ! -f "$output_file" ]] \
    || [[ "$state_was_present" == true && "$recorded_hash" != "$source_hash" ]] \
    || [[ ! -f "$output_file" && "$state_was_present" == true ]]; then
    needs_convert=true
  fi

  if $needs_convert; then
    tmp_output="$resources_dir/.${asset_name}.tmp.$$.m4a"
    rm -f "$tmp_output"
    if ! afconvert "$source_path" "$tmp_output" -f m4af -d aac -b "$bitrate" --soundcheck-generate >/dev/null \
      || [[ ! -s "$tmp_output" ]]; then
      rm -f "$tmp_output"
      echo "Failed to produce a valid music asset for '$id'." >&2
      exit 1
    fi
    mv -f "$tmp_output" "$output_file"
  fi
  awk -F$'\t' -v name="$asset_name" '$1 != name { print }' "$state_temp" > "$state_temp.next"
  printf '%s\t%s\n' "$asset_name" "$source_hash" >> "$state_temp.next"
  mv -f "$state_temp.next" "$state_temp"

  escaped_id="$(escape_swift_string "$id")"
  escaped_asset="$(escape_swift_string "$asset_name")"
  escaped_boss="$(escape_swift_string "$boss_enemy_id")"

  cat >> "$tracks_temp" <<SWIFT
        MusicTrack(
            id: "$escaped_id",
            kind: .$kind,
            resourceName: "$escaped_asset",
            fileExtension: "m4a",
            bossEnemyID: "$escaped_boss",
            isLooping: $looping,
            volumeGain: $volume_gain
        ),
SWIFT

  case "$kind" in
    menu)
      cat >> "$menu_temp" <<SWIFT
        "$escaped_id",
SWIFT
      ;;
    battle)
      cat >> "$battle_temp" <<SWIFT
        "$escaped_id",
SWIFT
      ;;
    boss)
      cat >> "$boss_temp" <<SWIFT
        "$escaped_boss": "$escaped_id",
SWIFT
      ;;
  esac

  processed_count=$((processed_count + 1))
done < "$manifest"

generated_temp=$(mktemp)
cat > "$generated_temp" <<SWIFT
// Generated by Scripts/prepare-music-assets.sh. Do not edit directly.

import Foundation

public enum MusicCatalog {
    public static let allTracks: [MusicTrack] = [
$(cat "$tracks_temp")
    ]

    public static let menuTrackIDs: [String] = [
$(cat "$menu_temp")
    ]

    public static let battleTrackIDs: [String] = [
$(cat "$battle_temp")
    ]

    public static let bossTrackIDByEnemyID: [String: String] = [
$(cat "$boss_temp")
    ]
}
SWIFT

if [[ -f "$generated_swift" ]] && cmp -s "$generated_temp" "$generated_swift"; then
  rm -f "$generated_temp"
else
  mv "$generated_temp" "$generated_swift"
fi

  # Prune orphaned music assets
  shopt -s nullglob
  for file in "$resources_dir"/*.m4a; do
    [[ -f "$file" ]] || continue
    filename=$(basename "$file")
    if ! grep -qx "$filename" "$active_tracks_temp"; then
      echo "Pruning orphaned music track: $filename"
      rm -f "$file"
    fi
  done
  shopt -u nullglob

{
  head -n 2 "$state_temp"
  tail -n +3 "$state_temp" | LC_ALL=C sort -t$'\t' -k1,1
} > "$state_temp.sorted"
mv -f "$state_temp.sorted" "$state_temp"
mv -f "$state_temp" "$state_file"
rm -f "$tracks_temp" "$menu_temp" "$battle_temp" "$boss_temp" "$seen_ids_temp" "$seen_assets_temp" "$seen_boss_ids_temp" "$active_tracks_temp"

echo "Prepared $processed_count music assets in $resources_dir and regenerated $generated_swift."
