"""Catalog-owned typed Swift resources and release metadata; no compiler or network needed."""
from __future__ import annotations

import json
from pathlib import Path
import re


def swift_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False).replace('\\/', '/')


def swift_resources(name: str, catalog: dict, resource_arguments: dict | None = None) -> str:
    from internal.localization import FORMAT, units
    ui = name.startswith('Trinket/') or any('/Sources/' + target + '/' in name for target in ('TrinketFeatureSupport', 'TrinketFeatureAdapters', 'TrinketBattleFeature'))
    bundle = '.main' if name.startswith('Trinket/') else '.atURL(Bundle.module.bundleURL)'
    lines = ['// Generated by Scripts/localization.py apply. Edit the English String Catalog.',
             'import Foundation', '', 'enum L10n {']
    if ui:
        lines.insert(2, 'import TrinketContent')
    for key, entry in sorted(catalog['strings'].items()):
        source = units(entry['localizations']['en'])
        text = source.get('other', source.get('value'))
        kinds = {}
        positions = []
        ordinal = 0
        for match in FORMAT.finditer(text):
            position, kind = match.groups()
            if kind == '%':
                continue
            if kind not in {'lld', '@'}:
                raise ValueError(f'{name}/{key}: unsupported native argument %{kind}; extend the typed resource contract before adding this format')
            ordinal += 1
            index = int(position) if position else ordinal
            positions.append(index)
            kinds[index] = 'String' if kind == '@' else 'Int'
            if index in (resource_arguments or {}).get(name + '::' + key, []):
                if kind != '@':
                    raise ValueError(f'{name}/{key}: resource arguments require %@ placeholders')
                kinds[index] = 'LocalizedStringResource'
        if positions != list(range(1, len(positions) + 1)):
            raise ValueError(f'{name}/{key}: English arguments must occur once in source order; use a separate typed argument for repeated values')
        if kinds and set(kinds) != set(range(1, len(kinds) + 1)):
            raise ValueError(f'{name}/{key}: placeholder positions must be contiguous')
        symbol = key.replace('.', '_')
        arguments = ', '.join(f'_ value{index}: {kind}' for index, kind in sorted(kinds.items()))
        ordinal = 0
        def replace(match):
            nonlocal ordinal
            position, kind = match.groups()
            if kind == '%':
                return '%'
            ordinal += 1
            index = int(position) if position else ordinal
            value = f'ContentCopy.localized(value{index})' if ui and kinds[index] == 'String' else f'value{index}'
            return f'\\({value})'
        escaped = swift_string(text)
        default = FORMAT.sub(replace, escaped)
        declaration = f'static func {symbol}({arguments}) -> LocalizedStringResource' if kinds else f'static var {symbol}: LocalizedStringResource'
        lines.extend([f'    {declaration} {{',
                      f'        LocalizedStringResource({swift_string(key)}, defaultValue: {default}, table: "Localizable", bundle: {bundle})',
                      '    }', ''])
    lines.extend(['}', ''])
    return '\n'.join(lines)


def generated_resources(root: Path, catalogs: dict) -> dict[Path, bytes]:
    result = {}
    config = json.loads((root / 'Localization/config.json').read_text())
    # XcodeGen derives knownRegions from localized source groups, not catalogs
    # inside synchronized folders. Empty generated markers declare the same
    # configured languages without duplicating any player-facing copy.
    for locale in ['en', *config['locales']]:
        result[root / f'Localization/Generated/Regions/{locale}.lproj/TrinketLanguages.strings'] = b'/* Generated locale declaration; translations live in String Catalogs. */\n'
    for name, catalog in catalogs.items():
        if name.startswith('Localization/'):
            continue
        parent = (root / name).parent.parent
        result[parent / 'Generated/LocalizedStrings.generated.swift'] = swift_resources(name, catalog, config.get('resourceArguments', {})).encode()
    if config.get('metadataCatalog'):
        from internal.localization_store import submission_files
        result.update(submission_files(root, config, catalogs[config['metadataCatalog']]))
    if config.get('contentCatalog'):
        from internal.localization_sources import content_sources, marked_template, numeric_source
        all_sources = content_sources(root)
        narratives = {key: entry for key, entry in all_sources.items() if 'narrative' in entry['context']}
        sources = {key: entry for key, entry in all_sources.items() if key not in narratives}
        # Runtime normalization of older canonical descriptions is a data compatibility boundary.
        sources = {key: dict(entry, original=entry['text'], text=entry['text'].replace('. ', '\n').replace('; ', '\n').rstrip('.;')) for key, entry in sources.items()}
        lines = ['// Generated by Scripts/localization.py apply. English remains in authored content.',
                 'import Foundation', 'import TrinketCore', '', 'public enum ContentCopy {',
                 '    public static func resource(_ english: String) -> LocalizedStringResource {',
                 '        match(english)?.resource ?? CoreCopy.resource(english)', '    }', '',
                 '    static func itemNameResource(_ baseID: String) -> LocalizedStringResource? {',
                 '        switch baseID {']
        for key in sorted(sources):
            if key.startswith('item_bases.') and key.endswith('.name'):
                lines.append(f'        case {swift_string(key.split(".")[1])}: L10n.{key.replace(".", "_")}')
        lines.extend(['        default: nil', '        }', '    }', ''])
        for group, method in [('traits', 'traitNameResource'), ('talents', 'talentNameResource')]:
            lines.extend([f'    static func {method}(_ id: String) -> LocalizedStringResource? {{', '        switch id {'])
            for key in sorted(sources):
                if key.startswith(group + '.') and key.endswith('.name'):
                    lines.append(f'        case {swift_string(key.split(".")[1])}: L10n.{key.replace(".", "_")}')
            lines.extend(['        default: nil', '        }', '    }', ''])
        lines.extend(['    public static func localized(_ english: String, locale: Locale = .current) -> String {',
                 '        description(english, locale: locale).text', '    }', '',
                 '    public static func description(_ english: String, locale: Locale = .current) -> LocalizedGameText {',
                 '        guard let match = match(english) else { return CoreCopy.description(english, locale: locale) }',
                 '        let values = Dictionary(uniqueKeysWithValues: match.quantities.enumerated().map { ("quantity_\\($0.offset + 1)", $0.element) })',
                 '        return LocalizedGameText(match.resource, locale: locale, values: values)', '    }', '',
                 '    private typealias Match = (resource: LocalizedStringResource, quantities: [Int])', '',
                 '    /// Exact text and saved numeric variants resolve once; rendering owns the locale and value spans.',
                 '    private static func match(_ english: String) -> Match? {',
                 '        switch english {'])
        # Explicit returns keep each branch independently type-checked; a single
        # inferred switch expression couples thousands of localized tuple results.
        seen = set()
        for key, entry in sorted(sources.items()):
            if entry['text'] in seen:
                continue
            seen.add(entry['text'])
            _, numbers = marked_template(root, entry['text'])
            args = '(' + ', '.join(map(str, numbers)) + ')' if numbers else ''
            quantities = '[' + ', '.join(map(str, numbers)) + ']'
            aliases = [swift_string(entry['text'])]
            if entry['original'] != entry['text'] and entry['original'] not in seen:
                aliases.append(swift_string(entry['original']))
                seen.add(entry['original'])
            lines.extend([f'        case {", ".join(aliases)}:',
                          f'            return (L10n.{key.replace(".", "_")}{args}, {quantities})'])
        lines.extend(['        default: return numericMatch(english)', '        }', '    }', '',
                      '    private struct NumericTemplate: Sendable {',
                      '        let prefix: String',
                      '        let regex: NSRegularExpression?',
                      '        let count: Int',
                      '        let make: @Sendable ([Int]) -> LocalizedStringResource', '    }', '',
                      '    private static let numericTemplates: [NumericTemplate] = ['])
        seen_patterns = set()
        for key, entry in sorted(sources.items()):
            _, numbers = marked_template(root, entry['text'])
            if not numbers:
                continue
            pieces = re.split(r'\d+', numeric_source(entry['text']))
            # Optional plurals are regex syntax, so only retain the literal
            # prefix preceding them for the cheap rejection path.
            prefix = re.split(r'\b(?:buff|debuff|card|turn|round)s?\b', pieces[0], maxsplit=1)[0]
            pattern = '^' + '([0-9]+)'.join(map(re.escape, pieces)) + '$'
            pattern = re.sub(r'\b(buff|debuff|card|turn|round)s?\b', r'\1s?', pattern)
            if pattern in seen_patterns:
                continue
            seen_patterns.add(pattern)
            args = ', '.join(f'values[{index}]' for index in range(len(numbers)))
            lines.append(f'        NumericTemplate(prefix: {swift_string(prefix)}, regex: try? NSRegularExpression(pattern: {swift_string(pattern)}), count: {len(numbers) }, make: {{ values in L10n.{key.replace(".", "_")}({args}) }}),')
        lines.extend(['    ]', '',
                      '    private static func numericMatch(_ english: String) -> Match? {',
                      '        guard english.contains(where: { $0.isNumber }), english.contains(" "), english.contains(where: { $0.isASCII && $0.isLetter }) else { return nil }',
                      '        let source = english as NSString',
                      '        let fullRange = NSRange(location: 0, length: source.length)',
                      '        for template in numericTemplates where english.hasPrefix(template.prefix) {',
                      '            guard let match = template.regex?.firstMatch(in: english, range: fullRange) else { continue }',
                      '            let numbers = (1 ... template.count).compactMap { Int(source.substring(with: match.range(at: $0))) }',
                      '            guard numbers.count == template.count else { continue }',
                      '            return (template.make(numbers), numbers)',
                      '        }', '        return nil', '    }', ''])
        lines.extend(['    public static func narrative(_ english: String, first: String, second: String, locale: Locale) -> String {', '        let resource: LocalizedStringResource', '        switch english {'])
        for key, entry in sorted(narratives.items()):
            args = ', '.join(value for marker, value in [('{A}', 'first'), ('{B}', 'second')] if marker in entry['text'])
            lines.append(f'        case {swift_string(entry["text"])}: resource = L10n.{key.replace(".", "_")}' + ('(' + args + ')' if args else ''))
        lines.extend(['        default: return localized(english, locale: locale)', '        }', '        return LocalizedGameText(resource, locale: locale).text', '    }', '}', ''])
        parent = (root / config['contentCatalog']).parent.parent
        result[parent / 'Generated/ContentCopy.generated.swift'] = '\n'.join(lines).encode()
    return result


def resource_errors(root: Path, *, catalogs: set[str] | None = None, paths: set[Path] | None = None) -> list[str]:
    from internal.localization import inventory
    errors = []
    if catalogs is None or catalogs:
        _, values, _ = inventory(root)
        scopes = None if catalogs is None else {(root / name).parent.parent.resolve() for name in catalogs}
        for path, expected in generated_resources(root, values).items():
            if scopes is not None and not any(path.resolve().is_relative_to(scope) for scope in scopes):
                continue
            if not path.exists() or path.read_bytes() != expected:
                errors.append(f'{path.relative_to(root)}: typed resources are missing or stale; run localization.py apply')
    from internal.localization_sources import source_errors
    config = json.loads((root / 'Localization/config.json').read_text())
    errors.extend(source_errors(root, paths=paths, check_content=catalogs is None or config.get('contentCatalog') in catalogs))
    return errors
